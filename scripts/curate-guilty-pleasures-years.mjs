const missing = deck.tracks.filter(track => !years[track.title])
if (missing.length) throw new Error(`Geen gecontroleerd jaar voor: ${missing.map(track => track.title).join(', ')}`)

for (const track of deck.tracks) {
  track.year = String(years[track.title])
  track.yearSource = 'Handmatig gecontroleerd'
  delete track.yearMatchScore
  track.tags = [...new Set([
    ...(track.tags || []).filter(tag => !/^\d{4}s$/.test(tag)),
    `${Math.floor(years[track.title] / 10) * 10}s`,
  ])]
}

